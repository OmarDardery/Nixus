'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'../admin/static');
const context=vm.createContext({document:{querySelector:()=>({})},setInterval:()=>0,URL});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../admin/static/projects.js'),'utf8'),context);
vm.runInContext(fs.readFileSync(path.join(root,'foundation.js'),'utf8'),context);
vm.runInContext(fs.readFileSync(path.join(root,'operations.js'),'utf8'),context);
const source=fs.readFileSync(path.join(root,'app.js'),'utf8');
vm.runInContext(source.slice(0,source.lastIndexOf('\n(async () =>')),context);
vm.runInContext(`
state.principal={username:'observer',role:'viewer'};
state.draft={backup:{enable:false,groups:[]}};
state.status={settings:{backup:{enable:false}},release:{revision:'a'.repeat(40)}};
operationView.archives=[{id:'a'.repeat(32),name:'<img src=x onerror=alert(1)>',project:'lab',created:1,available:true}];
`,context);
let html=vm.runInContext('operationsPage()',context);
assert.ok(!html.includes('data-guest-action='),'Viewer must not get guest mutation buttons');
assert.ok(!html.includes('data-download-recovery'),'Viewer must not get recovery export');
assert.ok(!html.includes('<script>bad'));
assert.ok(!html.includes('<img src=x'));
assert.equal(vm.runInContext('platformReview()',context),'');
vm.runInContext("state.principal={username:'admin',role:'admin'}",context);
html=vm.runInContext('operationsPage()',context);
assert.ok(!html.includes('data-guest-action='),'Guest controls belong exclusively to Incus');
assert.ok(!html.includes('snapshot-target'),'Snapshot controls belong exclusively to Incus');
assert.ok(!html.includes('data-run-backup') && !html.includes('restic-backups'),'One backup system: no legacy host backup controls');
// Staged Nix modules need password approval in Changes; there is no version picker there.
vm.runInContext("state.modules={'site-modules/x.nix':'{}'}",context);
const review=vm.runInContext('platformReview()',context);
assert.ok(review.includes('platform-password') && review.includes('platform-ack'));
assert.ok(!review.includes('data-load-main') && !review.includes('platform-revision'));
vm.runInContext("state.modules={}",context);
vm.runInContext("state.page='operations'", context);
assert.ok(vm.runInContext("title('', 'Backups', '')",context).includes('href="/docs/backups.md"'), 'Recovery guidance must stay local and available offline');
console.log('Operations UI checks passed: roles, escaped metadata, source approval and offline guides.');
vm.runInContext(`operationView.health={clock:{state:'plausible-but-unsynchronized',evidenceWarning:true,guidance:'Check <host> time'}}`,context);
const clockHtml=vm.runInContext('healthSummary()',context);
assert.ok(clockHtml.includes('plausible-but-unsynchronized'));
assert.ok(clockHtml.includes('Check &lt;host&gt; time'));
assert.ok(!clockHtml.includes('<host>'));
